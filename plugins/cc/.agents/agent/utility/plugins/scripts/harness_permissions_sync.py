#!/usr/bin/env python3
"""Keep every installed tj-agents package's declared harness permissions converged on this machine.

Enumerates every installed package from a marketplace owned by `tj-agents` across Claude's plugin scopes
(`installed_plugins.json` and `known_marketplaces.json`) and the Codex plugin cache and configuration,
renders each root's `harness.json` `requires.permissions` templates against that root, and converges
`~/.claude/settings.json` `permissions.allow` and `~/.codex/rules/tj-agents.rules`. Only the current
installed version of each package is rendered: Claude picks the most recently updated
`installPath` per identity from `installed_plugins.json`, Codex picks the most recently modified
version directory per cached plugin. Ownership is tracked in a `~/.agents-state/harness-permissions.json`
sidecar, so user-authored allow rules are never touched and owned rules that are no longer declared
(including rules for versions that are no longer current) are removed.
`--apply` writes only on drift; `--check` reports drift with exit 1 and writes nothing. An unreadable
host registry leaves that host's target untouched with a warning. `--print <script>` prints the exact
resolved invocation for a declared script (by filename) on this machine, one line per installed root,
for use in skill prose.

Setup runs `--apply`. Honours `CLAUDE_CONFIG_DIR`, `CODEX_HOME` and `AGENT_STATE_DIRECTORY` so tests
never touch real user files, and the opt-out `TJ_AGENTS_HARNESS_PERMISSIONS=off`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import harness_permissions


STATE_DIRECTORY_ENV = "AGENT_STATE_DIRECTORY"
OPT_OUT_ENV = "TJ_AGENTS_HARNESS_PERMISSIONS"
TRUSTED_OWNER = "tj-agents"
GITHUB_SOURCE = re.compile(
    r"(?:https://github\.com/|git@github\.com:|ssh://git@github\.com/)?"
    r"(?P<owner>[A-Za-z0-9-]+)/(?P<repo>[A-Za-z0-9_.-]+?)(?:\.git)?/?$",
    re.IGNORECASE,
)
MARKETPLACE_TABLE = re.compile(r'^\s*\[\s*marketplaces\.(?:"(?P<quoted>[^"]+)"|(?P<bare>[A-Za-z0-9_-]+))\s*\]')
STRING_ASSIGNMENT = re.compile(r'^\s*(?P<key>source_type|source|repository)\s*=\s*"(?P<value>[^"]*)"')
CODEX_RULES_NAME = "tj-agents.rules"
CODEX_RULES_HEADER = (
    "# Generated by tj-agents harness_permissions_sync; do not edit. "
    "User rules belong in other files."
)


class PermissionSyncError(RuntimeError):
    pass


def read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None


def _restore(path: Path, data: bytes | None) -> None:
    if data is None:
        if path.exists():
            _safe_path(path)
            path.unlink()
        return
    write_bytes_atomic(path, data)


def write_bytes_atomic(path: Path, data: bytes) -> None:
    _safe_path(path.parent)
    path.parent.mkdir(parents=True, exist_ok=True)
    _safe_path(path.parent)
    descriptor, temp = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
        _safe_path(path)
        os.replace(temp, str(path))
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def write_text_atomic(path: Path, text: str) -> None:
    write_bytes_atomic(path, text.encode("utf-8"))


def claude_config_root(environ: dict) -> Path:
    configured = environ.get("CLAUDE_CONFIG_DIR")
    return Path(configured).expanduser() if configured else Path.home() / ".claude"


def codex_home(environ: dict) -> Path:
    configured = environ.get("CODEX_HOME")
    return Path(configured).expanduser() if configured else Path.home() / ".codex"


def state_directory(environ: dict) -> Path:
    configured = environ.get(STATE_DIRECTORY_ENV)
    return Path(configured).expanduser() if configured else Path.home() / ".agents-state"


def sidecar_path(environ: dict) -> Path:
    return state_directory(environ) / "harness-permissions.json"


def github_repository(source: object) -> tuple[str, str] | None:
    match = GITHUB_SOURCE.fullmatch(source) if isinstance(source, str) else None
    if not match or match["repo"] in {".", ".."}:
        return None
    return match["owner"].casefold(), match["repo"].casefold()


def marketplace_repository(source: object) -> tuple[str, str] | None:
    if not isinstance(source, dict):
        return None
    if source.get("source") == "github":
        return github_repository(source.get("repo"))
    if source.get("source") == "git":
        return github_repository(source.get("url"))
    return None


def is_trusted_marketplace(source: object) -> bool:
    repository = marketplace_repository(source)
    return repository is not None and repository[0] == TRUSTED_OWNER


def _entry_recency(entry: dict) -> str:
    for key in ("lastUpdated", "installedAt"):
        value = entry.get(key)
        if isinstance(value, str) and value:
            return value
    return ""


def claude_plugin_roots(environ: dict, warnings: list[str]) -> tuple[set[Path], bool]:
    plugins_directory = claude_config_root(environ) / "plugins"
    path = plugins_directory / "installed_plugins.json"
    if not path.is_file():
        return set(), True
    data = read_json(path)
    plugins = data.get("plugins") if isinstance(data, dict) else None
    if not isinstance(plugins, dict):
        warnings.append(f"{path}: cannot read installed plugin registry; leaving the Claude target untouched")
        return set(), False
    known_path = plugins_directory / "known_marketplaces.json"
    known = read_json(known_path)
    if not isinstance(known, dict):
        warnings.append(f"{known_path}: cannot read marketplace registry; leaving the Claude target untouched")
        return set(), False
    roots: set[Path] = set()
    for identity, entries in plugins.items():
        if not isinstance(identity, str) or "@" not in identity:
            continue
        marketplace = identity.rsplit("@", 1)[1]
        marketplace_entry = known.get(marketplace)
        source = marketplace_entry.get("source") if isinstance(marketplace_entry, dict) else None
        if not is_trusted_marketplace(source):
            continue
        if not isinstance(entries, list):
            continue
        current: tuple[str, str] | None = None
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            install_path = entry.get("installPath")
            if not (isinstance(install_path, str) and install_path):
                continue
            candidate = (_entry_recency(entry), install_path)
            if current is None or candidate > current:
                current = candidate
        if current is not None:
            roots.add(Path(current[1]))
    return roots, True


def codex_marketplaces(environ: dict, warnings: list[str]) -> tuple[set[str], bool]:
    path = codex_home(environ) / "config.toml"
    if not path.is_file():
        return set(), True
    try:
        lines = path.read_text(encoding="utf-8-sig").splitlines()
    except (OSError, UnicodeError) as error:
        warnings.append(f"{path}: cannot read marketplace configuration ({error}); leaving the Codex rules untouched")
        return set(), False
    marketplaces: dict[str, dict[str, str]] = {}
    current: dict[str, str] | None = None
    for line in lines:
        table = MARKETPLACE_TABLE.match(line)
        if table:
            name = table["quoted"] or table["bare"]
            current = marketplaces.setdefault(name, {})
            continue
        if line.lstrip().startswith("["):
            current = None
            continue
        assignment = STRING_ASSIGNMENT.match(line)
        if current is not None and assignment:
            current[assignment["key"]] = assignment["value"]
    trusted = {
        name
        for name, values in marketplaces.items()
        if values.get("source_type") == "git"
        and is_trusted_marketplace({"source": "git", "url": values.get("source")})
    }
    return trusted, True


def codex_plugin_roots(environ: dict, warnings: list[str]) -> tuple[set[Path], bool]:
    trusted_marketplaces, marketplaces_ok = codex_marketplaces(environ, warnings)
    if not marketplaces_ok:
        return set(), False
    base = codex_home(environ) / "plugins" / "cache"
    roots: set[Path] = set()
    if not base.is_dir():
        return roots, True
    try:
        plugin_dirs = list(base.iterdir())
    except OSError as error:
        warnings.append(f"{base}: cannot list the Codex plugin cache ({error}); leaving the Codex rules untouched")
        return roots, False
    for marketplace_dir in plugin_dirs:
        if (
            not marketplace_dir.is_dir()
            or marketplace_dir.name.startswith("plugin-install-")
            or marketplace_dir.name not in trusted_marketplaces
        ):
            continue
        try:
            plugin_dirs = list(marketplace_dir.iterdir())
        except OSError:
            continue
        for plugin_dir in plugin_dirs:
            if not plugin_dir.is_dir() or plugin_dir.name.startswith("plugin-install-"):
                continue
            try:
                version_dirs = list(plugin_dir.iterdir())
            except OSError:
                continue
            current: tuple[float, str, Path] | None = None
            for version_dir in version_dirs:
                if not (version_dir.is_dir() and (version_dir / "harness.json").is_file()):
                    continue
                try:
                    modified = version_dir.stat().st_mtime
                except OSError:
                    modified = 0.0
                candidate = (modified, version_dir.name, version_dir)
                if current is None or candidate > current:
                    current = candidate
            if current is not None:
                roots.add(current[2])
    return roots, True


def load_requires(root: Path, warnings: list[str]) -> tuple[dict, dict] | None:
    harness = read_json(root / "harness.json")
    if not isinstance(harness, dict):
        return None
    requires = harness.get("requires")
    try:
        harness_permissions.validate_requires(requires, str(root))
    except Exception as error:  # noqa: BLE001
        warnings.append(f"{root}: ignoring invalid harness declaration ({error})")
        return None
    return harness, requires


def rendered_requirements(roots: set[Path], warnings: list[str]) -> list[dict]:
    requirements = []
    for root in sorted(roots):
        loaded = load_requires(root, warnings)
        if loaded is None:
            continue
        _, requires = loaded
        claude_allow, codex_rules = harness_permissions.render_permissions(requires["permissions"], root)
        requirements.append({"permissions": {"claude_allow": claude_allow, "codex_prefix_rules": codex_rules}})
    return requirements


def desired_permissions(environ: dict, warnings: list[str]) -> tuple[list[str], list[dict], bool, bool]:
    claude_roots, claude_ok = claude_plugin_roots(environ, warnings)
    codex_roots, codex_ok = codex_plugin_roots(environ, warnings)
    claude_allow, _ = harness_permissions.fold_permissions(rendered_requirements(claude_roots, warnings))
    _, codex_rules = harness_permissions.fold_permissions(rendered_requirements(codex_roots, warnings))
    return claude_allow, codex_rules, claude_ok, codex_ok


def _reparse(path: Path) -> bool:
    try:
        attributes = path.lstat().st_file_attributes
    except AttributeError:
        return path.is_symlink()
    return path.is_symlink() or bool(attributes & 0x400)


def _safe_path(path: Path) -> None:
    absolute = path.absolute()
    parts = absolute.parts
    current = Path(parts[0])
    for part in parts[1:]:
        current /= part
        if not current.exists() and not current.is_symlink():
            continue
        if _reparse(current):
            raise PermissionSyncError(f"refusing a reparse-point permission path: {current}")


def _strict_json(path: Path, label: str) -> dict:
    try:
        value = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as error:
        raise PermissionSyncError(f"{label}: cannot read JSON ({error})") from error
    if not isinstance(value, dict):
        raise PermissionSyncError(f"{label}: expected an object")
    return value


def _strict_sidecar(environ: dict) -> dict:
    path = sidecar_path(environ)
    if not path.is_file():
        return {"schema_version": 2, "claude": {}, "codex": {}}
    _safe_path(path)
    value = _strict_json(path, str(path))
    if value.get("schema_version") != 2 or not isinstance(value.get("claude"), dict) or not isinstance(value.get("codex"), dict):
        raise PermissionSyncError(f"{path}: invalid ownership sidecar")
    return value


def _claude_plan(path: Path, desired: list[str], sidecar: dict, warnings: list[str]) -> tuple[str | None, list[str]] | None:
    raw = path.read_text(encoding="utf-8-sig") if path.is_file() else None
    try:
        existing = json.loads(raw) if raw is not None else {}
    except ValueError as error:
        warnings.append(f"{path}: cannot parse settings ({error}); leaving untouched")
        return None
    permissions = existing.get("permissions", {}) if isinstance(existing, dict) else None
    allow = permissions.get("allow", []) if isinstance(permissions, dict) else None
    if not isinstance(allow, list) or any(not isinstance(entry, str) for entry in allow):
        warnings.append(f"{path}: settings, permissions or permissions.allow has an unexpected shape; leaving untouched")
        return None
    owned = sidecar["claude"].get(str(path), [])
    if not isinstance(owned, list) or any(not isinstance(entry, str) for entry in owned):
        raise PermissionSyncError(f"invalid Claude ownership entry for {path}")
    previously_owned = set(owned)
    survivors = [entry for entry in allow if entry not in previously_owned]
    user_authored = set(survivors)
    merged = survivors + [entry for entry in sorted(desired) if entry not in user_authored]
    now_owned = sorted(entry for entry in set(desired) if entry not in user_authored)
    if merged == allow:
        return None, now_owned
    permissions["allow"] = merged
    existing["permissions"] = permissions
    return json.dumps(existing, indent=2, ensure_ascii=False) + "\n", now_owned


def _codex_text(rules: list[dict]) -> str | None:
    if not rules:
        return None
    return "\n".join([CODEX_RULES_HEADER, "", *harness_permissions.codex_rule_lines(rules)])


def _owned_codex(path: Path, sidecar: dict, header: str) -> bool:
    if not path.is_file():
        return False
    _safe_path(path)
    current = hashlib.sha256(path.read_bytes()).hexdigest().upper()
    if sidecar["codex"].get(str(path)) == current:
        return True
    try:
        return path.read_text(encoding="utf-8-sig").startswith(header)
    except (OSError, UnicodeError) as error:
        raise PermissionSyncError(f"{path}: cannot read existing Codex rules ({error})") from error


def _codex_plan(environ: dict, rules: list[dict], sidecar: dict) -> list[tuple[Path, str | None]]:
    directory = codex_home(environ) / "rules"
    path = directory / CODEX_RULES_NAME
    text = _codex_text(rules)
    changes: list[tuple[Path, str | None]] = []
    current = path.read_text(encoding="utf-8-sig") if path.is_file() else None
    if current != text:
        if path.exists() and not _owned_codex(path, sidecar, CODEX_RULES_HEADER):
            raise PermissionSyncError(f"{path}: refusing to replace unowned Codex rules")
        changes.append((path, text))
    return changes


def synchronize(environ: dict, mode: str) -> tuple[list[str], list[str]]:
    if mode not in {"apply", "check"}:
        raise PermissionSyncError(f"unsupported mode: {mode}")
    warnings: list[str] = []
    if environ.get(OPT_OUT_ENV, "").strip().casefold() == "off":
        return [], [f"{OPT_OUT_ENV}=off; harness permissions were not synchronized"]
    claude_allow, codex_rules, claude_ok, codex_ok = desired_permissions(environ, warnings)
    state = sidecar_path(environ)
    _safe_path(state)
    sidecar = _strict_sidecar(environ)
    changes: list[str] = []
    writes: list[tuple[Path, str | None]] = []
    if claude_ok:
        path = claude_config_root(environ) / "settings.json"
        _safe_path(path)
        plan = _claude_plan(path, claude_allow, sidecar, warnings)
        if plan is not None:
            text, owned = plan
            if text is not None:
                writes.append((path, text))
                changes.append(f"converge Claude permissions.allow in {path}")
            if owned:
                sidecar["claude"][str(path)] = owned
            else:
                sidecar["claude"].pop(str(path), None)
    if codex_ok:
        for path, text in _codex_plan(environ, codex_rules, sidecar):
            writes.append((path, text))
            changes.append(f"{'write' if text is not None else 'remove'} Codex rules {path}")
            if text is None:
                sidecar["codex"].pop(str(path), None)
            else:
                sidecar["codex"][str(path)] = hashlib.sha256(text.encode("utf-8")).hexdigest().upper()
    sidecar["schema_version"] = 2
    after = json.dumps(sidecar, indent=2, ensure_ascii=False) + "\n"
    current_state = state.read_text(encoding="utf-8-sig") if state.is_file() else None
    untracked = current_state is None and not sidecar["claude"] and not sidecar["codex"]
    if after != current_state and not untracked:
        writes.append((state, after))
        if not changes:
            changes.append(f"record harness permission ownership in {state}")
    if mode == "check":
        return changes, warnings
    before = [path.read_bytes() if path.is_file() else None for path, _ in writes]
    completed = 0
    try:
        for path, text in writes:
            if text is None:
                _safe_path(path)
                path.unlink()
            else:
                write_text_atomic(path, text)
            completed += 1
    except Exception as error:
        failures = []
        for (path, _text), original in zip(writes[:completed], before[:completed]):
            try:
                _restore(path, original)
            except Exception as rollback:
                failures.append(f"{path} ({rollback})")
        if failures:
            raise PermissionSyncError(
                f"permission update failed ({error}) and rollback failed for: {', '.join(failures)}") from error
        raise PermissionSyncError(f"permission update failed ({error})") from error
    return changes, warnings


def print_invocations(environ: dict, script_name: str) -> tuple[list[str], list[str]]:
    warnings: list[str] = []
    claude_roots, _ = claude_plugin_roots(environ, warnings)
    codex_roots, _ = codex_plugin_roots(environ, warnings)
    roots = sorted(claude_roots | codex_roots)
    lines: list[str] = []
    for root in roots:
        loaded = load_requires(root, warnings)
        if loaded is None:
            continue
        _, requires = loaded
        for template in requires["permissions"]["claude_allow"]:
            if not (template.startswith("Bash(") and template.endswith(")")):
                continue
            inner = template[len("Bash("):-1]
            if script_name not in inner:
                continue
            forward, _ = harness_permissions.path_spellings(root)
            rendered = inner.replace(harness_permissions.PLUGIN_ROOT_TOKEN, forward)
            if rendered not in lines:
                lines.append(rendered)
    return lines, warnings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--apply", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--print", dest="print_script", metavar="SCRIPT")
    args = parser.parse_args(argv)
    environ = dict(os.environ)
    try:
        if args.print_script:
            lines, warnings = print_invocations(environ, args.print_script)
            for line in lines:
                print(line)
            for warning in warnings:
                print(f"harness-permissions-sync: {warning}", file=sys.stderr)
            return 0
        changes, warnings = synchronize(environ, "apply" if args.apply else "check")
    except (PermissionSyncError, OSError, UnicodeError) as error:
        print(f"harness-permissions-sync: {error}", file=sys.stderr)
        return 2
    for warning in warnings:
        print(f"harness-permissions-sync: {warning}", file=sys.stderr)
    for change in changes:
        print(("would " if args.check else "") + change)
    return 1 if args.check and changes else 0


if __name__ == "__main__":
    raise SystemExit(main())
