"""The per-host native session contract and its dispatch table (Python 3.9+)."""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Protocol

from claude import sessions as claude_sessions
from codex import sessions as codex_sessions
from host import Host


class Sessions(Protocol):
    HOST: Host
    FRONTEND_FROM_REGISTRATION: bool
    FRONTEND_STATE: tuple[str, ...]

    def history_roots(self, root: Path) -> tuple[Path, ...]: ...

    def transcript_files(self, directory: Path) -> Iterable[Path]: ...

    def transcript_ids(self, path: Path) -> tuple[str, ...]: ...

    def read_session(self, path: Path) -> dict | None: ...

    def header(self, path: Path) -> dict | None: ...

    def recoverable(self, item: dict) -> bool: ...

    def resume_command(self, session_id: str) -> str: ...

    def open_tab(self, cli, item: dict, directory, label: str, instruction: str, status_path: Path, *, model=None,
                 native_arguments=(), dangerously_skip_permissions=False) -> None: ...

    def prepare_frontend(self, arguments, project: Path, environment, executable=None): ...

    def attach_frontend(self, ticket, pid: int) -> None: ...

    def release_frontend(self, ticket) -> None: ...

    def debug_arguments(self, arguments: list[str], directory: Path) -> tuple[list[str], str | None]: ...

    def native_arguments(self, argv: list[str]) -> list[str]: ...

    def validate_relaunch(self, entry: dict, project: Path) -> None: ...

    def check_relaunch(self, project: Path, executable: str, native: list[str], session_id: str, prompt: str) -> None: ...

    def close_arguments(self, entry: dict) -> list[str]: ...

    def own_entry(self, nearest, cwd: Path, session_id: str | None, shared) -> dict | None: ...

    def verify_frontend(self, entry: dict, shared) -> None: ...

    def completes(self, state: dict, data: dict, turn_id: str | None) -> bool: ...

    def prepared_record(self, record: dict, session_id: str, shared) -> dict: ...

    def close_target(self, session_id: str, supplied: Path | None) -> dict: ...

    def arm_close(self, entry: dict, turn_id: str | None, target: dict, supplied: Path | None, shared) -> dict: ...

    def close_monitor(self, request: dict, shared): ...

    def settled(self, request: dict, monitor, completed: bool, shared): ...

    def close_guard(self, request: dict, activity, completed: bool, shared) -> None: ...


SESSIONS: Mapping[Host, Sessions] = {Host.CLAUDE: claude_sessions, Host.CODEX: codex_sessions}
